// Extra services next to Apache/PHP/MySQL: Mailpit (catches outgoing mail)
// and Redis (cache/queues/sessions). Both are optional downloads into bin/.

func (a *App) firstBin(explicit string, patterns ...string) string {
	if explicit != "" {
		return a.abs(explicit)
	}
	for _, pat := range patterns {
		m, _ := filepath.Glob(pat)
		sort.Strings(m)
		if len(m) > 0 {
			return m[len(m)-1]
		}
	}
	return ""
}

func (a *App) mailpitBin(cfg *Config) string {
	if cfg.Mailpit.Bin == "" && cfg.Mailpit.Dir != "" {
		return filepath.Join(a.abs(cfg.Mailpit.Dir), exeName("mailpit"))
	}
	return a.firstBin(cfg.Mailpit.Bin)
}

func (a *App) redisBin(cfg *Config) string {
	if cfg.Redis.Bin == "" && cfg.Redis.Dir != "" {
		return filepath.Join(a.abs(cfg.Redis.Dir), exeName("redis-server"))
	}
	return a.firstBin(cfg.Redis.Bin)
}

func installed(bin string) bool { return bin != "" && exists(bin) }

func (a *App) mailpitCmd(cfg *Config) (*exec.Cmd, error) {
	bin := a.mailpitBin(cfg)
	if !installed(bin) {
		return nil, errors.New("Mailpit is not installed")
	}
	data := a.path("data", "mailpit")
	if err := os.MkdirAll(data, 0o755); err != nil {
		return nil, err
	}
	cmd := hiddenCommand(bin,
		"--smtp", fmt.Sprintf("127.0.0.1:%d", cfg.Mailpit.SMTPPort),
		"--listen", fmt.Sprintf("127.0.0.1:%d", cfg.Mailpit.UIPort),
		"--database", filepath.Join(data, "mailpit.db"))
	cmd.Dir = filepath.Dir(bin)
	return cmd, nil
}

func (a *App) renderRedisConf(cfg *Config) string {
	return fmt.Sprintf(`# Generated by Omni Web Server. Put overrides in etc/redis/custom.conf
port %d
bind %s
protected-mode yes
daemonize no
dir "%s"
dbfilename dump.rdb
save 900 1
save 300 10
appendonly no
logfile ""
`, cfg.Redis.Port, loopbackAddrs(" "), slash(a.path("data", "redis")))
}

// hasIPv6Loopback reports whether ::1 can be bound. Servers listen on it too
// so that "localhost" (which Windows resolves to ::1 first) connects at once.
func hasIPv6Loopback() bool {
	ln, err := net.Listen("tcp6", "[::1]:0")
	if err != nil {
		return false
	}
	ln.Close()
	return true
}

// loopbackAddrs is "127.0.0.1" plus "::1" when available, joined by sep.
func loopbackAddrs(sep string) string {
	if hasIPv6Loopback() {
		return "127.0.0.1" + sep + "::1"
	}
	return "127.0.0.1"
}

func (a *App) redisCmd(cfg *Config) (*exec.Cmd, error) {
	bin := a.redisBin(cfg)
	if !installed(bin) {
		return nil, errors.New("Redis is not installed")
	}
	if err := os.MkdirAll(a.path("data", "redis"), 0o755); err != nil {
		return nil, err
	}
	conf := a.renderRedisConf(cfg)
	if custom := a.path("etc", "redis", "custom.conf"); exists(custom) {
		conf += fmt.Sprintf("include \"%s\"\n", slash(custom))
	}
	confPath := a.path("etc", "redis", "redis.conf")
	if _, err := writeIfChanged(confPath, []byte(conf)); err != nil {
		return nil, err
	}
	cmd := hiddenCommand(bin, confPath)
	cmd.Dir = filepath.Dir(bin)
	return cmd, nil
}

func (a *App) redisShutdown(cfg *Config) error {
	cli := filepath.Join(filepath.Dir(a.redisBin(cfg)), exeName("redis-cli"))
	if !exists(cli) {
		return errors.New("redis-cli not found")
	}
	return hiddenCommand(cli, "-p", fmt.Sprint(cfg.Redis.Port), "shutdown").Run()
}

// discoverServices registers Mailpit/Redis/Node found in bin/ (or on PATH off Windows).
func (a *App) discoverServices(cfg *Config) {
	if cfg.Mailpit.Dir == "" && cfg.Mailpit.Bin == "" {
		if b := a.firstBin("", a.path("bin", "mailpit", "*", exeName("mailpit")), a.path("bin", "mailpit", exeName("mailpit"))); b != "" {
			cfg.Mailpit.Dir = a.rel(filepath.Dir(b))
		} else if runtime.GOOS != "windows" {
			if p, err := exec.LookPath("mailpit"); err == nil {
				cfg.Mailpit.Bin = p
			}
		}
	}
	if cfg.Redis.Dir == "" && cfg.Redis.Bin == "" {
		if b := a.firstBin("", a.path("bin", "redis", "*", exeName("redis-server")), a.path("bin", "redis", "*", "*", exeName("redis-server"))); b != "" {
			cfg.Redis.Dir = a.rel(filepath.Dir(b))
		} else if runtime.GOOS != "windows" {
			if p, err := exec.LookPath("redis-server"); err == nil {
				cfg.Redis.Bin = p
			}
		}
	}
	if b := a.mailpitBin(cfg); b != "" && !exists(b) {
		cfg.Mailpit.Dir, cfg.Mailpit.Bin = "", ""
	}
	if b := a.redisBin(cfg); b != "" && !exists(b) {
		cfg.Redis.Dir, cfg.Redis.Bin = "", ""
	}
	nodes, _ := filepath.Glob(a.path("bin", "node", "*", exeName("node")))
	for _, n := range nodes {
		if v := versionRe.FindString(filepath.Base(filepath.Dir(n))); v != "" {
			if _, ok := cfg.Node.Versions[v]; !ok {
				cfg.Node.Versions[v] = a.rel(filepath.Dir(n))
			}
		}
	}
	for v, dir := range cfg.Node.Versions {
		if !exists(filepath.Join(a.abs(dir), exeName("node"))) {
			delete(cfg.Node.Versions, v)
		}
	}
}

var redisVersionRe = regexp.MustCompile(`v=([\d.]+)`)
var mailpitVersionRe = regexp.MustCompile(`v?(\d+\.\d+\.\d+)`)

// ---- installers ----

func (a *App) installMailpit(t *Task, customURL string) error {
	u := customURL
	if u == "" {
		if runtime.GOOS != "windows" {
			return errors.New("on Linux/macOS install Mailpit with its install script or package manager; it is detected on PATH")
		}
		u = "https://github.com/axllent/mailpit/releases/latest/download/mailpit-windows-amd64.zip"
	}
	if a.mailpit.Running() {
		_ = a.mailpit.Stop()
	}
	dir, err := a.installZip(t, u, "", "", "mailpit", "mailpit", exeName("mailpit"))
	if err != nil {
		return err
	}
	a.forgetVersion("mailpit")
	if err := a.update(func(c *Config) error { c.Mailpit.Dir, c.Mailpit.Bin = a.rel(dir), ""; return nil }); err != nil {
		return err
	}
	t.Set("Mailpit installed; starting it", 0.99)
	return a.mailpit.Start()
}

var redisAssetRe = regexp.MustCompile(`(?i)^redis-[\d.]+-windows-x64[^"]*\.zip$`)

// latestRedisURL asks GitHub for the newest redis-windows build (MSYS2 variant preferred).
func latestRedisURL() (string, error) {
	body, err := fetchText("https://api.github.com/repos/redis-windows/redis-windows/releases/latest")
	if err != nil {
		return "", err
	}
	var rel struct {
		Assets []struct {
			Name string `json:"name"`
			URL  string `json:"browser_download_url"`
		} `json:"assets"`
	}
	if err := json.Unmarshal([]byte(body), &rel); err != nil {
		return "", err
	}
	best := ""
	for _, as := range rel.Assets {
		n := strings.ToLower(as.Name)
		if !redisAssetRe.MatchString(as.Name) || strings.Contains(n, "service") {
			continue
		}
		if best == "" || strings.Contains(n, "msys2") {
			best = as.URL
		}
	}
	if best == "" {
		return "", errors.New("no Windows Redis build found; use 'install from URL'")
	}
	return best, nil
}

func (a *App) installRedis(t *Task, customURL string) error {
	u := customURL
	if u == "" {
		if runtime.GOOS != "windows" {
			return errors.New("on Linux/macOS install redis-server with your package manager; it is detected on PATH")
		}
		t.Set("Looking up the latest Redis for Windows", -1)
		var err error
		if u, err = latestRedisURL(); err != nil {
			return err
		}
	}
	if a.redis.Running() {
		_ = a.redis.Stop()
	}
	name := "redis-" + versionRe.FindString(filepath.Base(u))
	dir, err := a.installZip(t, u, "", "", "redis", name, exeName("redis-server"))
	if err != nil {
		return err
	}
	a.forgetVersion("redis")
	if err := a.update(func(c *Config) error { c.Redis.Dir, c.Redis.Bin = a.rel(dir), ""; return nil }); err != nil {
		return err
	}
	t.Set("Redis installed; starting it", 0.99)
	return a.redis.Start()
}

func (a *App) forgetVersion(key string) {
	a.mu.Lock()
	delete(a.versions, key)
	a.mu.Unlock()
}
