// Modules DevStack wants; each is loaded only if Apache has it as a shared object.
var apacheModules = []string{
	"authn_core", "authn_file", "auth_basic", "authz_core", "authz_host", "authz_user", "access_compat",
	"mime", "dir", "alias", "rewrite", "headers", "expires", "deflate", "filter", "env", "setenvif",
	"log_config", "autoindex", "version", "unixd",
	"proxy", "proxy_fcgi",
}

type apacheModule struct{ Name, Path string }

type apacheVhost struct {
	Name, Host, DocRoot, Pool string
	Cert, Key                 string // set when the site is served over HTTPS
}

type apacheInput struct {
	ServerRoot string
	Root       string
	WWW        string
	Logs       string
	Tmp        string
	MimeTypes  string
	CustomDir  string
	Port       int
	Modules    []apacheModule
	Default    string // FastCGI address of the default PHP version
	Vhosts     []apacheVhost
	HTTPSPort  int // 0 = HTTPS off
	LocalCert  [2]string
	Windows    bool
	User       string
	Group      string
}

func slash(p string) string { return filepath.ToSlash(p) }

// phpAddress is where Apache sends PHP requests for a version (DevStack's dispatcher).
func phpAddress(minor string) string { return fmt.Sprintf("127.0.0.1:%d", phpPortBase(minor)) }

func phpHandler(b *strings.Builder, addr, indent string) {
	if addr == "" {
		return
	}
	fmt.Fprintf(b, "%s<FilesMatch \"\\.php$\">\n", indent)
	fmt.Fprintf(b, "%s    <If \"-f %%{REQUEST_FILENAME}\">\n", indent)
	fmt.Fprintf(b, "%s        SetHandler \"proxy:fcgi://%s\"\n", indent, addr)
	fmt.Fprintf(b, "%s    </If>\n", indent)
	fmt.Fprintf(b, "%s</FilesMatch>\n", indent)
}

func dirBlock(b *strings.Builder, dir, indent string) {
	fmt.Fprintf(b, "%s<Directory \"%s\">\n", indent, slash(dir))
	fmt.Fprintf(b, "%s    Options Indexes FollowSymLinks\n", indent)
	fmt.Fprintf(b, "%s    AllowOverride All\n", indent)
	fmt.Fprintf(b, "%s    Require all granted\n", indent)
	fmt.Fprintf(b, "%s    CGIPassAuth On\n", indent)
	fmt.Fprintf(b, "%s</Directory>\n", indent)
}

func renderApacheConf(in apacheInput) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# Generated by DevStack. Do not edit: changes are overwritten.")
	w("# Put your own directives in %s/*.conf", slash(in.CustomDir))
	w("")
	w("ServerRoot \"%s\"", slash(in.ServerRoot))
	w("DefaultRuntimeDir \"%s\"", slash(in.Tmp))
	w("PidFile \"%s\"", slash(filepath.Join(in.Tmp, "httpd.pid")))
	w("Listen %d", in.Port)
	if in.HTTPSPort != 0 {
		w("Listen %d", in.HTTPSPort)
	}
	w("ServerName localhost")
	w("ServerAdmin admin@localhost")
	w("")
	for _, m := range in.Modules {
		w("LoadModule %s_module \"%s\"", m.Name, slash(m.Path))
	}
	w("")
	if in.User != "" {
		w("User %s", in.User)
		w("Group %s", in.Group)
	}
	if in.Windows {
		w("AcceptFilter http none")
		w("AcceptFilter https none")
		w("ThreadsPerChild 150")
	}
	w("Timeout 300")
	w("KeepAlive On")
	w("HostnameLookups Off")
	w("EnableSendfile off")
	w("ErrorLog \"%s\"", slash(filepath.Join(in.Logs, "apache_error.log")))
	w("LogLevel warn")
	w(`LogFormat "%%v %%h %%l %%u %%t \"%%r\" %%>s %%b \"%%{Referer}i\" \"%%{User-Agent}i\"" vcombined`)
	w("CustomLog \"%s\" vcombined", slash(filepath.Join(in.Logs, "apache_access.log")))
	if in.MimeTypes != "" {
		w("TypesConfig \"%s\"", slash(in.MimeTypes))
	}
	w("AddType application/x-httpd-php .php")
	w("DirectoryIndex index.php index.html index.htm")
	w("ProxyTimeout 300")
	w("ProxyFCGIBackendType GENERIC")
	if in.HTTPSPort != 0 {
		w("SSLProtocol -all +TLSv1.2 +TLSv1.3")
		w("SSLSessionCache \"shmcb:%s(512000)\"", slash(filepath.Join(in.Tmp, "ssl_scache")))
		w("SSLSessionCacheTimeout 300")
	}
	w("")
	w("<Directory />")
	w("    AllowOverride None")
	w("    Require all denied")
	w("</Directory>")
	w("<FilesMatch \"^\\.(ht|env|git)\">")
	w("    Require all denied")
	w("</FilesMatch>")
	w("")
	vhost := func(port int, name, alias, docroot, pool, cert, key string) {
		w("<VirtualHost *:%d>", port)
		w("    ServerName %s", name)
		w("    ServerAlias %s", alias)
		w("    DocumentRoot \"%s\"", slash(docroot))
		if cert != "" {
			w("    SSLEngine on")
			w("    SSLCertificateFile \"%s\"", slash(cert))
			w("    SSLCertificateKeyFile \"%s\"", slash(key))
		}
		dirBlock(&b, docroot, "    ")
		phpHandler(&b, pool, "    ")
		w("</VirtualHost>")
	}
	w("# Default host: http://localhost/ lists the projects in www")
	vhost(in.Port, "localhost", "127.0.0.1", in.WWW, in.Default, "", "")
	if in.HTTPSPort != 0 && in.LocalCert[0] != "" {
		vhost(in.HTTPSPort, "localhost", "127.0.0.1", in.WWW, in.Default, in.LocalCert[0], in.LocalCert[1])
	}
	for _, v := range in.Vhosts {
		w("")
		w("# %s", v.Name)
		vhost(in.Port, v.Host, "*."+v.Host, v.DocRoot, v.Pool, "", "")
		if in.HTTPSPort != 0 && v.Cert != "" {
			vhost(in.HTTPSPort, v.Host, "*."+v.Host, v.DocRoot, v.Pool, v.Cert, v.Key)
		}
	}
	w("")
	w("IncludeOptional \"%s/*.conf\"", slash(in.CustomDir))
	return b.String()
}

// apacheBin returns the httpd binary, or "" when Apache is not installed.
func (a *App) apacheBin(cfg *Config) string {
	if cfg.Apache.Bin != "" {
		return a.abs(cfg.Apache.Bin)
	}
	if cfg.Apache.Dir == "" {
		return ""
	}
	return filepath.Join(a.abs(cfg.Apache.Dir), "bin", exeName("httpd"))
}

func (a *App) apacheModulesDir(cfg *Config) string {
	if cfg.Apache.ModulesDir != "" {
		return a.abs(cfg.Apache.ModulesDir)
	}
	if cfg.Apache.Dir != "" {
		return filepath.Join(a.abs(cfg.Apache.Dir), "modules")
	}
	return ""
}

var staticModRe = regexp.MustCompile(`mod_(\w+)\.c`)

// apacheStaticModules lists modules compiled into httpd (httpd -l), cached per binary.
func (a *App) apacheStaticModules(bin string) map[string]bool {
	a.mu.Lock()
	if m, ok := a.staticMods[bin]; ok {
		a.mu.Unlock()
		return m
	}
	a.mu.Unlock()
	m := map[string]bool{}
	out, _ := hiddenCommand(bin, "-l").CombinedOutput()
	for _, match := range staticModRe.FindAllStringSubmatch(string(out), -1) {
		m[match[1]] = true
	}
	if strings.Contains(string(out), "event.c") {
		m["mpm_event"] = true
	}
	if strings.Contains(string(out), "prefork.c") {
		m["mpm_prefork"] = true
	}
	if strings.Contains(string(out), "worker.c") {
		m["mpm_worker"] = true
	}
	if strings.Contains(string(out), "mpm_winnt.c") {
		m["mpm_winnt"] = true
	}
	a.mu.Lock()
	a.staticMods[bin] = m
	a.mu.Unlock()
	return m
}

func (a *App) apacheModuleList(cfg *Config, ssl bool) []apacheModule {
	bin := a.apacheBin(cfg)
	dir := a.apacheModulesDir(cfg)
	static := a.apacheStaticModules(bin)
	var mods []apacheModule
	add := func(name string) bool {
		if static[name] {
			return true
		}
		p := filepath.Join(dir, "mod_"+name+".so")
		if exists(p) {
			mods = append(mods, apacheModule{name, p})
			return true
		}
		return false
	}
	if !static["mpm_winnt"] && !static["mpm_event"] && !static["mpm_prefork"] && !static["mpm_worker"] {
		if !add("mpm_event") {
			add("mpm_prefork")
		}
	}
	for _, m := range apacheModules {
		add(m)
	}
	if ssl {
		add("socache_shmcb")
		add("ssl")
	}
	return mods
}

func (a *App) apacheMimeTypes(cfg *Config) string {
	if cfg.Apache.MimeTypes != "" {
		return a.abs(cfg.Apache.MimeTypes)
	}
	if cfg.Apache.Dir != "" {
		if p := filepath.Join(a.abs(cfg.Apache.Dir), "conf", "mime.types"); exists(p) {
			return p
		}
	}
	for _, p := range []string{"/etc/mime.types", "/etc/apache2/mime.types", "/etc/httpd/conf/mime.types"} {
		if exists(p) {
			return p
		}
	}
	return ""
}

func (a *App) apacheServerRoot(cfg *Config) string {
	if cfg.Apache.Dir != "" {
		return a.abs(cfg.Apache.Dir)
	}
	return a.path("etc", "apache")
}

// apacheRunAs picks an unprivileged user when DevStack runs as root on Unix.
func apacheRunAs() (string, string) {
	if runtime.GOOS == "windows" || os.Geteuid() != 0 {
		return "", ""
	}
	for _, pair := range [][2]string{{"www-data", "www-data"}, {"apache", "apache"}, {"http", "http"}, {"nobody", "nogroup"}, {"nobody", "nobody"}} {
		if _, err := user.Lookup(pair[0]); err != nil {
			continue
		}
		if _, err := user.LookupGroup(pair[1]); err != nil {
			continue
		}
		return pair[0], pair[1]
	}
	return "", ""
}

func (a *App) apacheConfPath() string { return a.path("etc", "apache", "httpd.conf") }

func (a *App) buildApacheConf(cfg *Config, sites []Site, certs map[string][2]string) string {
	usr, grp := apacheRunAs()
	in := apacheInput{
		ServerRoot: a.apacheServerRoot(cfg),
		Root:       a.root,
		WWW:        a.abs(cfg.WWWDir),
		Logs:       a.path("logs"),
		Tmp:        a.path("tmp"),
		MimeTypes:  a.apacheMimeTypes(cfg),
		CustomDir:  a.path("etc", "apache", "custom"),
		Port:       cfg.HTTPPort,
		Modules:    a.apacheModuleList(cfg, certs != nil),
		Windows:    runtime.GOOS == "windows",
		User:       usr,
		Group:      grp,
	}
	if cfg.DefaultPHP != "" {
		in.Default = phpAddress(cfg.DefaultPHP)
	}
	if certs != nil {
		in.HTTPSPort = cfg.HTTPSPort
		in.LocalCert = certs["localhost"]
	}
	for _, s := range sites {
		if !s.Enabled || s.Missing {
			continue
		}
		pool := ""
		if s.PHP != "" {
			pool = phpAddress(s.PHP)
		}
		c := certs[s.Host]
		in.Vhosts = append(in.Vhosts, apacheVhost{Name: s.Name, Host: s.Host, DocRoot: s.DocRoot, Pool: pool, Cert: c[0], Key: c[1]})
	}
	return renderApacheConf(in)
}

// testApacheConf runs httpd -t against a config file.
func testApacheConf(bin, conf string) error {
	out, err := hiddenCommand(bin, "-t", "-f", conf).CombinedOutput()
	if err != nil {
		return fmt.Errorf("apache config test failed: %s", strings.TrimSpace(string(out)))
	}
	return nil
}

func (a *App) apacheCmd(cfg *Config) (*exec.Cmd, error) {
	bin := a.apacheBin(cfg)
	if bin == "" || !exists(bin) {
		return nil, fmt.Errorf("apache is not installed")
	}
	cmd := hiddenCommand(bin, "-f", a.apacheConfPath(), "-DFOREGROUND")
	cmd.Dir = filepath.Dir(bin)
	return cmd, nil
}

var apacheVersionRe = regexp.MustCompile(`Apache/([\d.]+)`)

func binVersion(bin string, re *regexp.Regexp, args ...string) string {
	if bin == "" || !exists(bin) {
		return ""
	}
	out, _ := hiddenCommand(bin, args...).CombinedOutput()
	if m := re.FindStringSubmatch(string(out)); m != nil {
		return m[1]
	}
	return ""
}
