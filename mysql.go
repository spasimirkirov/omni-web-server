func (a *App) mysqlBin(cfg *Config) string {
	if cfg.MySQL.Bin != "" {
		return a.abs(cfg.MySQL.Bin)
	}
	if cfg.MySQL.Dir == "" {
		return ""
	}
	bin := filepath.Join(a.abs(cfg.MySQL.Dir), "bin")
	for _, n := range []string{"mysqld", "mariadbd"} {
		if p := filepath.Join(bin, exeName(n)); exists(p) {
			return p
		}
	}
	return filepath.Join(bin, exeName("mysqld"))
}

// mysqlTool finds a companion binary (mysql, mysqladmin, ...) next to the server.
func (a *App) mysqlTool(cfg *Config, names ...string) string {
	server := a.mysqlBin(cfg)
	if server == "" {
		return ""
	}
	dirs := []string{filepath.Dir(server)}
	if runtime.GOOS != "windows" {
		dirs = append(dirs, "/usr/bin", "/usr/local/bin", "/usr/sbin")
	}
	for _, d := range dirs {
		for _, n := range names {
			if p := filepath.Join(d, exeName(n)); exists(p) {
				return p
			}
		}
	}
	return ""
}

func (a *App) mysqlFlavor(cfg *Config) string {
	if cfg.MySQL.Flavor != "" {
		return cfg.MySQL.Flavor
	}
	bin := a.mysqlBin(cfg)
	if strings.Contains(strings.ToLower(filepath.Base(bin)), "mariadb") || a.mysqlTool(cfg, "mariadb-install-db", "mysql_install_db") != "" && strings.Contains(strings.ToLower(bin), "maria") {
		return "mariadb"
	}
	if strings.Contains(strings.ToLower(binVersion(bin, regexp.MustCompile(`(?i)(mariadb)`), "--version")), "mariadb") {
		return "mariadb"
	}
	return "mysql"
}

func (a *App) mysqlDataDir(cfg *Config) string {
	if cfg.MySQL.DataDir != "" {
		return a.abs(cfg.MySQL.DataDir)
	}
	return a.path("data", "mysql")
}

func (a *App) mysqlIniPath() string { return a.path("etc", "mysql", "my.ini") }

func (a *App) renderMyIni(cfg *Config) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	sock := slash(a.path("tmp", "mysql.sock"))
	w("# Generated by Omni Web Server. Put overrides in etc/mysql/custom.ini")
	w("[mysqld]")
	if cfg.MySQL.Dir != "" {
		w("basedir = \"%s\"", slash(a.abs(cfg.MySQL.Dir)))
	}
	w("datadir = \"%s\"", slash(a.mysqlDataDir(cfg)))
	w("port = %d", cfg.MySQL.Port)
	w("bind-address = 127.0.0.1")
	if runtime.GOOS != "windows" {
		w("socket = \"%s\"", sock)
		w("pid-file = \"%s\"", slash(a.path("tmp", "mysqld.pid")))
		if os.Geteuid() == 0 {
			w("user = root")
		}
	}
	w("log-error = \"%s\"", slash(a.path("logs", "mysql_error.log")))
	w("character-set-server = utf8mb4")
	w("collation-server = utf8mb4_unicode_ci")
	w("max_allowed_packet = 256M")
	w("innodb_buffer_pool_size = 256M")
	w("max_connections = 200")
	w("")
	w("[client]")
	w("port = %d", cfg.MySQL.Port)
	w("host = 127.0.0.1")
	if runtime.GOOS != "windows" {
		w("socket = \"%s\"", sock)
	}
	w("default-character-set = utf8mb4")
	if custom := a.path("etc", "mysql", "custom.ini"); exists(custom) {
		w("")
		w("!include %s", slash(custom))
	}
	return b.String()
}

// initMySQLData creates the system tables on first start (root without password).
func (a *App) initMySQLData(cfg *Config) error {
	data := a.mysqlDataDir(cfg)
	if entries, err := os.ReadDir(data); err == nil && len(entries) > 0 {
		return nil
	}
	if err := os.MkdirAll(data, 0o755); err != nil {
		return err
	}
	var cmd *exec.Cmd
	if a.mysqlFlavor(cfg) == "mariadb" {
		tool := a.mysqlTool(cfg, "mariadb-install-db", "mysql_install_db")
		if tool == "" {
			return fmt.Errorf("mariadb-install-db not found")
		}
		if runtime.GOOS == "windows" {
			_ = os.Remove(data) // the Windows installer wants to create the folder itself
			cmd = hiddenCommand(tool, "--datadir="+data, fmt.Sprintf("--port=%d", cfg.MySQL.Port))
		} else {
			args := []string{"--defaults-file=" + a.mysqlIniPath(), "--auth-root-authentication-method=normal", "--skip-test-db"}
			if cfg.MySQL.Dir != "" {
				args = append(args, "--basedir="+a.abs(cfg.MySQL.Dir))
			}
			cmd = hiddenCommand(tool, args...)
		}
	} else {
		cmd = hiddenCommand(a.mysqlBin(cfg), "--defaults-file="+a.mysqlIniPath(), "--initialize-insecure", "--console")
	}
	out, err := cmd.CombinedOutput()
	_ = os.WriteFile(a.path("logs", "mysql_init.log"), out, 0o644)
	if err != nil {
		_ = os.RemoveAll(data)
		return fmt.Errorf("initializing MySQL data failed: %v\n%s", err, tailString(string(out), 1500))
	}
	return nil
}

func (a *App) mysqlCmd(cfg *Config) (*exec.Cmd, error) {
	bin := a.mysqlBin(cfg)
	if bin == "" || !exists(bin) {
		return nil, fmt.Errorf("MySQL is not installed")
	}
	if _, err := writeIfChanged(a.mysqlIniPath(), []byte(a.renderMyIni(cfg))); err != nil {
		return nil, err
	}
	if err := a.initMySQLData(cfg); err != nil {
		return nil, err
	}
	args := []string{"--defaults-file=" + a.mysqlIniPath()}
	if runtime.GOOS == "windows" {
		args = append(args, "--standalone")
	}
	cmd := hiddenCommand(bin, args...)
	cmd.Dir = filepath.Dir(bin)
	return cmd, nil
}

// mysqlClientArgs connects as root over TCP using the configured password.
func (a *App) mysqlClientArgs(cfg *Config) []string {
	return []string{"--no-defaults", "-h", "127.0.0.1", "-P", fmt.Sprint(cfg.MySQL.Port), "-u", "root", "--password=" + cfg.MySQL.RootPassword}
}

func (a *App) mysqlShutdown(cfg *Config) error {
	tool := a.mysqlTool(cfg, "mysqladmin", "mariadb-admin")
	if tool == "" {
		return fmt.Errorf("mysqladmin not found")
	}
	out, err := hiddenCommand(tool, append(a.mysqlClientArgs(cfg), "shutdown")...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("%v: %s", err, out)
	}
	return nil
}

// mysqlExec runs one SQL statement with the mysql client and returns stdout.
func (a *App) mysqlExec(cfg *Config, sql string) (string, error) {
	tool := a.mysqlTool(cfg, "mysql", "mariadb")
	if tool == "" {
		return "", fmt.Errorf("mysql client not found")
	}
	cmd := hiddenCommand(tool, append(a.mysqlClientArgs(cfg), "-N", "-B", "-e", sql)...)
	out, err := cmd.Output()
	if err != nil {
		msg := err.Error()
		if ee, ok := err.(*exec.ExitError); ok {
			msg = strings.TrimSpace(string(ee.Stderr))
		}
		return "", fmt.Errorf("%s", msg)
	}
	return string(out), nil
}

var dbNameRe = regexp.MustCompile(`^[A-Za-z0-9_$-]{1,64}$`)

var systemDatabases = map[string]bool{"information_schema": true, "mysql": true, "performance_schema": true, "sys": true}

func (a *App) listDatabases(cfg *Config) ([]string, error) {
	out, err := a.mysqlExec(cfg, "SHOW DATABASES")
	if err != nil {
		return nil, err
	}
	var dbs []string
	for _, l := range strings.Split(out, "\n") {
		if l = strings.TrimSpace(l); l != "" && !systemDatabases[l] {
			dbs = append(dbs, l)
		}
	}
	return dbs, nil
}

func (a *App) createDatabase(cfg *Config, name string) error {
	if !dbNameRe.MatchString(name) {
		return fmt.Errorf("invalid database name")
	}
	_, err := a.mysqlExec(cfg, "CREATE DATABASE IF NOT EXISTS `"+name+"` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci")
	return err
}

func (a *App) dropDatabase(cfg *Config, name string) error {
	if !dbNameRe.MatchString(name) || systemDatabases[name] {
		return fmt.Errorf("invalid database name")
	}
	_, err := a.mysqlExec(cfg, "DROP DATABASE `"+name+"`")
	return err
}

func (a *App) setRootPassword(cfg *Config, pw string) error {
	q := strings.ReplaceAll(strings.ReplaceAll(pw, `\`, `\\`), `'`, `\'`)
	sql := ""
	for _, host := range []string{"localhost", "127.0.0.1", "::1"} {
		sql += fmt.Sprintf("ALTER USER IF EXISTS 'root'@'%s' IDENTIFIED BY '%s'; ", host, q)
	}
	sql += "FLUSH PRIVILEGES;"
	_, err := a.mysqlExec(cfg, sql)
	return err
}

var mysqlVersionRe = regexp.MustCompile(`Ver ([\d.]+)(-MariaDB)?`)

func tailString(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return "..." + s[len(s)-n:]
}
